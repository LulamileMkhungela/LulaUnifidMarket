'use strict';

/**
 * Regenerate docs/06-api-reference.md from the routes that are actually
 * registered. The document claims it cannot drift from the code; this script is
 * what makes that true.
 *
 *   npm run docs:api           # rewrite docs/06-api-reference.md
 *   npm run docs:api -- --check  # fail if the committed document is stale
 */

const fs = require('fs');
const path = require('path');

const { buildApiRoutes } = require('../src/server/routes/api');
const { Marketplace } = require('../src/marketplace');

const HEADER = `# API reference

{routeCount} operations across {pathCount} paths, generated by
\`npm run docs:api\` straight from the registered route table so this document
cannot drift from the code. The machine-readable OpenAPI 3.1 document is served
live at \`GET /api/openapi.json\` and can be printed with \`npm run openapi\`.

Conventions:

- All amounts are **integer cents** in ZAR unless a field name says otherwise.
- All timestamps are ISO-8601 UTC.
- Errors are \`{ error, message, details?, policyDecision?, correlationId }\`
  with a meaningful HTTP status: **400** for a validation failure (the message
  lists the fields), **404** for a record that does not exist, **409** for a
  policy refusal or state conflict (with \`policyDecision\` and the rules that
  fired), **500** for anything else — with a correlation id and never a stack
  trace.
- Reads are cacheable by the service worker; writes are network-only and queued
  offline.
- Server-rendered public pages live beside the API: \`/sites\`, \`/s/<slug>\`,
  \`/preview/<slug>\`, \`/export/<slug>\`, \`/p/<pro-slug>\`, \`/trust\`, \`/admin\`,
  \`/robots.txt\`, \`/sitemap.xml\`.
`;

const TAG_NOTES = {
  platform: 'Health, the public snapshot, the offline bundle and platform telemetry.',
  catalogue: 'Categories, price guidance, geography and the resolution of plain language into a category.',
  people: 'Registration, the 9-stage pro verification pipeline, channels, sessions and bank-detail changes.',
  trust: 'The ledger, verification outcomes, the published rule book and integrity receipts.',
  jobs: 'Posting, matching, amending, awarding and expiring jobs.',
  bidding: 'Bids, Fair-Price Intelligence and the re-bid window.',
  bookings: 'Escrow funding, arrival codes, geosealed proof of work, confirmation and release.',
  disputes: 'Opening, evidence and resolution.',
  reviews: 'Verified-only reviews and the manipulation scanner.',
  vehicles: 'The merged TrustShield vertical: listings, checks, negotiation locks, handover and the Service Passport.',
  webstudio: 'The custom website packages, the free pro microsite and the rescue diagnostic.',
  sites: 'The Business Site Studio: templates, plans, build, assets, permissions, publishing, bookings, money and export.',
  sales: 'The sales desk: leads, diagnostics, demos, pitch kits, consent and the pipeline.',
  money: 'Routes that move or hold money — every one of them writes a MONEY-level ledger entry.',
  public: 'Routes a member of the public can call with no session: generated sites and their booking forms.',
  integrations: 'Every external dependency, its mode, and a live probe.',
  admin: 'The trust desk: queues, risk, escrow position and the scheduler.',
  safety: 'Rules that protect a person rather than a transaction.',
  compliance: 'POPIA, consent and statutory obligations.',
  'public-data': 'Bundled or free public datasets.',
  support: 'Help tickets with photo evidence and SLA targets.',
  demo: 'Scripts and fixtures for demonstrations.',
};

function generate() {
  const marketplace = new Marketplace();
  const router = buildApiRoutes({ marketplace });

  const groups = new Map();
  for (const route of router.routes) {
    const tag = (route.meta.tags && route.meta.tags[0]) || 'platform';
    if (!groups.has(tag)) groups.set(tag, []);
    groups.get(tag).push(route);
  }

  const pathCount = new Set(router.routes.map((r) => r.pattern)).size;
  const out = [HEADER
    .replace('{routeCount}', String(router.routes.length))
    .replace('{pathCount}', String(pathCount))];

  for (const [tag, routes] of groups) {
    out.push(`\n## ${tag}\n`);
    if (TAG_NOTES[tag]) out.push(`${TAG_NOTES[tag]}\n`);
    out.push('| Method | Route | Purpose |');
    out.push('| --- | --- | --- |');
    for (const route of routes) {
      const summary = (route.meta.summary || '').replace(/\|/g, '\\|');
      const extra = [route.meta.auth ? 'authenticated' : null, (route.meta.tags || []).length > 1 ? route.meta.tags.slice(1).join(', ') : null]
        .filter(Boolean).join(' · ');
      out.push(`| \`${route.method}\` | \`${route.pattern}\` | ${summary}${extra ? ` _(${extra})_` : ''} |`);
    }
    out.push('');
  }

  out.push(`\n---\n\nGenerated ${new Date().toISOString().slice(0, 10)} from ${router.routes.length} registered routes.\n`);
  return out.join('\n');
}

const file = path.join(__dirname, '..', 'docs', '06-api-reference.md');
const document = generate();

if (process.argv.includes('--check')) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (current.trim() !== document.trim()) {
    process.stderr.write('docs/06-api-reference.md is stale — run `npm run docs:api`\n');
    process.exit(1);
  }
  process.stdout.write('docs/06-api-reference.md is current\n');
} else {
  fs.writeFileSync(file, document);
  process.stdout.write(`wrote ${file} (${document.split('\n').length} lines)\n`);
}
